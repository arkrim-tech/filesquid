/**
 * Write `src/api/contract-version.ts` from the contract's `info.version`, so the version that
 * Settings, About shows ("API: {status} · contract {version}", UI-S-033) moves with the
 * generated types. `npm run contract:types` runs it after regenerating `src/api/schema.d.ts`;
 * the contract drift test fails while the two differ.
 *
 * Usage: `node tests/support/write-contract-version.mjs [<openapi.json>]`
 * The default contract path is `../crates/api/openapi.json`, relative to the package. Exits
 * with status 1 when the contract cannot be read or has no `info.version`.
 */
import { readFileSync, writeFileSync } from "node:fs";

const TARGET = "src/api/contract-version.ts";

/**
 * Read the contract's version.
 *
 * @param {string} path - Path of the OpenAPI document.
 * @returns {string} Its `info.version`.
 * @throws {Error} When the file is missing, is not JSON or has no string `info.version`.
 */
function contractVersion(path) {
  const version = JSON.parse(readFileSync(path, "utf8"))?.info?.version;
  if (typeof version !== "string") throw new Error(`${path} has no info.version`);
  return version;
}

/**
 * The module text that exports the version.
 *
 * @param {string} version - The contract version.
 * @returns {string} The TypeScript source.
 */
function moduleText(version) {
  return `/**
 * The version of the FileSquid API contract (\`crates/api/openapi.json\`, \`info.version\`) this
 * package's generated types target. Settings, About shows it as "API: {status} · contract
 * {version}" (UI-S-033, owner answer 12). Generated by \`npm run contract:types\`
 * (\`tests/support/write-contract-version.mjs\`); the contract drift test fails when it differs
 * from the committed contract.
 */
export const CONTRACT_VERSION = "${version}";
`;
}

try {
  writeFileSync(
    TARGET,
    moduleText(contractVersion(process.argv[2] ?? "../crates/api/openapi.json")),
  );
} catch (error) {
  console.error(`write-contract-version: ${error instanceof Error ? error.message : error}`);
  process.exitCode = 1;
}
