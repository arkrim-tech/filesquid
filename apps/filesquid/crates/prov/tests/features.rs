/// Lines of the manifest table `table`, comments and blanks skipped.
fn manifest_table<'a>(manifest: &'a str, table: &str) -> Vec<&'a str> {
    let mut inside = false;
    let mut lines = Vec::new();
    for line in manifest.lines().map(str::trim) {
        if line.starts_with('[') {
            inside = line == table;
        } else if inside && !line.is_empty() && !line.starts_with('#') {
            lines.push(line);
        }
    }
    lines
}

#[then("no default dependency should be another FileSquid crate")]
fn then_no_default_dep(world: &mut ProvWorld) {
    for line in manifest_table(&world.manifest, "[dependencies]") {
        let filesquid = line.starts_with("filesquid");
        assert!(!filesquid || line.contains("optional = true"), "{line}");
    }
}

#[then("no feature should name filesquid-native or filesquid-c2pa")]
fn then_no_feature(world: &mut ProvWorld) {
    for line in manifest_table(&world.manifest, "[features]") {
        for never in [
            "filesquid-native",
            "filesquid_native",
            "filesquid-c2pa",
            "filesquid_c2pa",
        ] {
            assert!(!line.contains(never), "{line}");
        }
    }
}

