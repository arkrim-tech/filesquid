/// Marker planted in tampered values; no error message may repeat it.
const SECRET: &str = "SECRET-4410";

/// World state for the PROV-O model scenarios.
#[derive(Debug, Default, World)]
struct ProvWorld {
    /// Facts the next build step uses.
    facts: Option<VersionFacts>,
    /// Record built by the last build step.
    record: Option<Record>,
    /// Serialized documents from the last serialization step.
    documents: Vec<String>,
    /// Record read back by the round-trip step.
    parsed: Option<Record>,
    /// Stored record text the parse step reads.
    stored: String,
    /// Outcome of the last parse step.
    parse_outcome: Option<Result<Record, ProvError>>,
    /// History index of the index scenarios.
    index: Option<HistoryIndex>,
    /// Activity IDs read page by page.
    paged: Vec<String>,
    /// Last page read.
    last_page: Option<Page>,
    /// Whether the last page request was accepted.
    page_accepted: Option<bool>,
    /// Manifest text read by the isolation step.
    manifest: String,
    /// Outcome of the wasm32 build check.
    wasm_build: Option<Result<(), String>>,
}

impl ProvWorld {
    /// The record of the last build step.
    fn record(&self) -> &Record {
        self.record.as_ref().expect("a record was built")
    }

    /// Entity identifier of `path` in `version` of the fixture object.
    fn eid(version: &str, path: &str) -> String {
        entity_id(OBJECT, version, path)
    }
}

#[given(expr = "the facts of version {string} of an object whose base version is {string}")]
fn given_facts(world: &mut ProvWorld, version: String, base: String) {
    let facts = standard_facts();
    assert_eq!(
        (facts.version.as_str(), facts.base_version.as_deref()),
        (version.as_str(), Some(base.as_str()))
    );
    world.facts = Some(facts);
}

#[given("the caller observed no installation and no host")]
fn given_unobserved(world: &mut ProvWorld) {
    let facts = world.facts.as_mut().expect("facts");
    facts.installation = None;
    facts.host = None;
}

#[when("I build its PROV-O record")]
fn when_build(world: &mut ProvWorld) {
    let facts = world.facts.as_ref().expect("facts");
    world.record = Some(build_record(facts).expect("build"));
}

#[then("the record should hold exactly one prov:Activity named after the operation, object and version")]
fn then_one_activity(world: &mut ProvWorld) {
    let text = to_json_ld(world.record());
    assert_eq!(text.matches("\"prov:Activity\"").count(), 1);
    let expected = format!("urn:filesquid:activity:{OPERATION}:{OBJECT}:v3");
    assert_eq!(world.record().activity().id(), expected);
}

#[then("its end time should equal the version's created time")]
fn then_end_time(world: &mut ProvWorld) {
    let created = world.facts.as_ref().expect("facts").created.clone();
    assert_eq!(world.record().activity().ended_at().as_str(), created);
}

#[then("it should name the journal entry IDs of the commit")]
fn then_journal(world: &mut ProvWorld) {
    assert_eq!(world.record().activity().journal_entries(), ["j-1", "j-2"]);
}

#[then("the changed path should be generated by the activity and derived from its previous state")]
fn then_changed(world: &mut ProvWorld) {
    let record = world.record();
    let new = record
        .entity(&ProvWorld::eid("v3", "a.txt"))
        .expect("changed");
    assert_eq!(new.generated_by(), Some(record.activity().id()));
    assert_eq!(new.derived_from(), [ProvWorld::eid("v2", "a.txt")]);
}

#[then("the moved path should be derived from the old path's previous state")]
fn then_moved(world: &mut ProvWorld) {
    let moved = world
        .record()
        .entity(&ProvWorld::eid("v3", "new/c.txt"))
        .expect("moved");
    assert_eq!(moved.derived_from(), [ProvWorld::eid("v2", "old/c.txt")]);
}

#[then("the removed path's previous state should be invalidated by the activity")]
fn then_removed(world: &mut ProvWorld) {
    let record = world.record();
    let removed = record
        .entity(&ProvWorld::eid("v2", "b.txt"))
        .expect("removed");
    assert_eq!(removed.invalidated_by(), Some(record.activity().id()));
}

#[then("every previous state the activity replaced should be used by it")]
fn then_used(world: &mut ProvWorld) {
    let used = world.record().activity().used();
    assert_eq!(
        used,
        [
            ProvWorld::eid("v2", "a.txt"),
            ProvWorld::eid("v2", "old/c.txt")
        ]
    );
}

#[then("every entity should carry its object ID, version, logical path and SHA-256 digest")]
fn then_entity_facts(world: &mut ProvWorld) {
    for entity in world.record().entities() {
        assert_eq!(entity.object_id(), OBJECT);
        assert_eq!(
            entity.id(),
            entity_id(OBJECT, entity.version(), entity.path())
        );
        assert_eq!(entity.sha256().len(), 64);
    }
}

#[then(expr = "the activity should be associated with {string} followed by the installation UUID")]
fn then_installation(world: &mut ProvWorld, prefix: String) {
    let id = format!("{prefix}{INSTALLATION}");
    assert!(world.record().activity().associated_with().contains(&id));
    let agent = world.record().agent(&id).expect("installation agent");
    assert!(matches!(agent.kind(), AgentKind::Installation(_)));
}

#[then("the FileSquid host should be a prov:SoftwareAgent acting on behalf of the installation")]
fn then_host(world: &mut ProvWorld) {
    let host = world
        .record()
        .agents()
        .iter()
        .find(|a| matches!(a.kind(), AgentKind::Host(_)));
    let host = host.expect("host agent");
    let installation = format!("urn:uuid:{INSTALLATION}");
    assert_eq!(host.acted_on_behalf_of(), Some(installation.as_str()));
    assert!(to_json_ld(world.record()).contains("\"@type\":\"prov:SoftwareAgent\""));
}

#[then("the record should contain no prov:Person and no display name")]
fn then_no_person(world: &mut ProvWorld) {
    let text = to_json_ld(world.record());
    for banned in ["prov:Person", "schema:name", "rdfs:label", "foaf:"] {
        assert!(!text.contains(banned), "{banned}");
    }
}

#[then("both agents should be stated as unrecorded")]
fn then_unrecorded(world: &mut ProvWorld) {
    let kinds: Vec<AgentKind> = world
        .record()
        .agents()
        .iter()
        .map(|a| a.kind().clone())
        .collect();
    assert_eq!(
        kinds,
        [
            AgentKind::Unrecorded(AgentRole::Host),
            AgentKind::Unrecorded(AgentRole::Installation)
        ]
    );
}

#[when("I serialize the record twice from equal facts")]
fn when_serialize_twice(world: &mut ProvWorld) {
    let facts = world.facts.as_ref().expect("facts");
    world.documents = (0..2)
        .map(|_| to_json_ld(&build_record(facts).expect("build")))
        .collect();
}

#[then("both documents should be byte-for-byte equal")]
fn then_equal_bytes(world: &mut ProvWorld) {
    assert_eq!(world.documents[0].as_bytes(), world.documents[1].as_bytes());
}

#[then("the graph should list the activity first, then agents and entities sorted by identifier")]
fn then_graph_order(world: &mut ProvWorld) {
    let doc: Value = serde_json::from_str(&world.documents[0]).expect("json");
    let graph = doc["@graph"].as_array().expect("graph");
    assert_eq!(graph[0]["@type"], "prov:Activity");
    let ids: Vec<&str> = graph
        .iter()
        .map(|n| n["@id"].as_str().expect("id"))
        .collect();
    assert!(ids[1..3].windows(2).all(|w| w[0] < w[1]));
    assert!(ids[3..].windows(2).all(|w| w[0] < w[1]));
}

#[when("I serialize the record and parse it again")]
fn when_round_trip(world: &mut ProvWorld) {
    let record = build_record(world.facts.as_ref().expect("facts")).expect("build");
    world.parsed = Some(parse_record(to_json_ld(&record).as_bytes()).expect("parse"));
    world.record = Some(record);
}

#[then("the parsed record should equal the original")]
fn then_round_trip(world: &mut ProvWorld) {
    assert_eq!(world.parsed.as_ref(), Some(world.record()));
}

/// The standard record as text with `defect` applied.
fn defective_record(facts: &VersionFacts, defect: &str) -> String {
    let text = to_json_ld(&build_record(facts).expect("build"));
    let mut doc: Value = serde_json::from_str(&text).expect("json");
    match defect {
        "is larger than 1 MiB" => format!("{text}{}", " ".repeat(1_048_577)),
        "nests deeper than 16 levels" => {
            let mut nested = json!(SECRET);
            for _ in 0..14 {
                nested = json!({ "k": nested });
            }
            doc["@graph"][0]["fsq:kind"] = nested;
            doc.to_string()
        }
        "repeats a key" => text.replacen(
            "\"fsq:kind\":\"move\"",
            &format!("\"fsq:kind\":\"move\",\"fsq:kind\":\"{SECRET}\""),
            1,
        ),
        "names an unknown profile" => text.replacen("filesquid-prov/1", SECRET, 1),
        "holds an entity with a forged ID" => {
            doc["@graph"][3]["fsq:path"] = json!(SECRET);
            doc.to_string()
        }
        other => panic!("unknown defect {other}"),
    }
}

#[given(expr = "a stored record that {}")]
fn given_defect(world: &mut ProvWorld, defect: String) {
    world.stored = defective_record(world.facts.as_ref().expect("facts"), defect.trim());
}

#[when("I parse it")]
fn when_parse(world: &mut ProvWorld) {
    world.parse_outcome = Some(parse_record(world.stored.as_bytes()));
}

#[then(expr = "parsing should fail with {string}")]
fn then_parse_code(world: &mut ProvWorld, code: String) {
    let outcome = world.parse_outcome.as_ref().expect("parsed");
    let err = outcome.as_ref().expect_err("refused");
    assert_eq!(err.code(), code);
}

#[then("the error message should name no stored value")]
fn then_no_value(world: &mut ProvWorld) {
    let outcome = world.parse_outcome.as_ref().expect("parsed");
    let message = outcome.as_ref().expect_err("refused").to_string();
    assert!(!message.contains(SECRET), "{message}");
}

/// Record of `version` of `object` committed by `operation`, ending at `ended`.
fn indexed_record(object: &str, version: u32, operation: &str, ended: &str) -> Record {
    let mut facts = first_version_facts(object, operation, ended);
    facts.version = format!("v{version}");
    if version > 1 {
        facts.base_version = Some(format!("v{}", version - 1));
        facts.base_state = state(&[("a.txt", 'a')]);
        facts.new_state = state(&[("a.txt", 'b')]);
    }
    build_record(&facts).expect("build")
}

/// First object of the index scenarios.
const FIRST: &str = "urn:uuid:aaaaaaaa-aaaa-4aaa-8aaa-aaaaaaaaaaaa";

#[given("an index of 5 activities across 2 objects")]
fn given_index(world: &mut ProvWorld) {
    let second = "urn:uuid:bbbbbbbb-bbbb-4bbb-8bbb-bbbbbbbbbbbb";
    let mut index = HistoryIndex::new();
    for record in [
        indexed_record(FIRST, 1, "op-1", "2026-10-19T10:00:00Z"),
        indexed_record(second, 1, "op-2", "2026-10-19T10:00:01Z"),
        indexed_record(FIRST, 2, "op-3", "2026-10-19T10:00:02Z"),
        indexed_record(second, 2, "op-3", "2026-10-19T10:00:02Z"),
        indexed_record(FIRST, 3, "op-4", "2026-10-19T10:00:03Z"),
    ] {
        index.insert(record).expect("insert");
    }
    world.index = Some(index);
}

#[when(expr = "I read the activities of the first object in pages of {int}")]
fn when_page(world: &mut ProvWorld, size: usize) {
    let index = world.index.as_ref().expect("index");
    let query = HistoryQuery::Object(FIRST.to_string());
    let mut cursor = None;
    for _ in 0..10 {
        let page = index.query(&query, &PageRequest::new(size, cursor).expect("size"));
        world
            .paged
            .extend(page.items().iter().map(|a| a.id().to_string()));
        cursor = page.next().cloned();
        world.last_page = Some(page);
        if cursor.is_none() {
            return;
        }
    }
    panic!("paging did not end");
}

#[then(expr = "I should read {int} activities ordered by end time then activity ID")]
fn then_paged(world: &mut ProvWorld, count: usize) {
    let expected: Vec<String> = ["op-1:v1", "op-3:v2", "op-4:v3"]
        .iter()
        .map(|pair| {
            let (op, version) = pair.split_once(':').expect("pair");
            filesquid_prov::activity_id(op, FIRST, version)
        })
        .collect();
    assert_eq!(world.paged.len(), count);
    assert_eq!(world.paged, expected);
}

